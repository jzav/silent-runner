#include "HelpGenerator.h"

#include "SRTypes.h"

namespace HelpGenerator {

std::wstring Generate() {
    std::wstring err =
        L"Usage of v1.2.0:\n"
        L"  SilentRunner.exe [options] <script-or-exe> [args...]\n"
        L"      Script/Executable mode: execute a script or executable via cmd.exe /d /s /c.\n"
        L"      The file must be executable in the user's Windows environment.\n"
        L"      Some characters may trigger cmd.exe shell operations or affect interpretation:\n"
        L"      chaining (&, &&, ||), output piping (|), redirection (>, <),\n"
        L"      grouping ( ), escaping (^), or variable expansion (%...%, !...!)\n"
        L"      Their presence may be logged for debugging.\n"
        L"      For complex command logic, use a .cmd or other script file (multi-line supported).\n"
        L"  SilentRunner.exe [options] -c \"<command>\"\n"
        L"      Command-string mode: execute a single command string via cmd.exe /d /s /c.\n"
        L"      The command must be passed as a single \"<command>\" argument.\n"
        L"\n"
        L"Completion:\n"
        L"      Normal completion requires the main child, managed process tree, and both readers to finish.\n"
        L"      The reported child exit code comes from the main child; descendant exit codes are not combined.\n"
        L"\n"
        L"Paths:\n"
        L"      Quote paths containing spaces when passing them as CLI arguments.\n"
        L"      Relative paths supplied to SilentRunner path options are resolved against SilentRunner's current working directory\n"
        L"      (inherited from the parent process). --cwd sets the working directory for child execution and run hooks.\n"
        L"      For environment variable expansion and cmd.exe path resolution rules, see:\n"
        L"      https://github.com/jzav/silent-runner/blob/main/docs/execution.md#execution-modes\n"
        L"\n"
        L"Process Environment:\n"
        L"  --cwd <dir>\n"
        L"      Set the working directory for the main child process and run-on-* hooks.\n"
        L"      If omitted, SilentRunner uses its inherited working directory.\n"
        L"      The specified directory must already exist; it is not created.\n"
        L"  --inherit-stdin\n"
        L"      Inherit parent stdin instead of using NUL.\n"
        L"  --utf8 or --utf-8\n"
        L"      Force UTF-8 code page (chcp 65001) for the child process.\n"
        L"  --timeout-ms <ms>\n"
        L"      Set the Runtime timeout in milliseconds, including descendants and stdout/stderr draining.\n"
        L"      On timeout, abort the process tree and stop pending readers.\n"
        L"      After successful tree termination, both readers share a 2-second drain grace period.\n"
        L"      Pending reads are then cancelled; shutdown may take longer.\n"
        L"  --abort-on-runtime-failure\n"
        L"      Request termination of the managed process tree if the infrastructure needed to supervise\n"
        L"      execution through completion and obtain the main child exit code fails.\n"
        L"      If runtime supervision fails, SilentRunner does not terminate the child process or its\n"
        L"      process tree unless --abort-on-runtime-failure is enabled. Runtime exit code: 255.\n"
        L"      Successful tree termination uses the same shared reader-drain grace period.\n"

        L"\n"
        L"Execution ID:\n"
        L"  --id-prefix <value>\n"
        L"  --id-base <value>\n"
        L"  --id-suffix <timestamp|pid|timestamp+pid|pid+timestamp>\n"
        L"      All three components are optional and may be used independently.\n"
        L"      The execution ID is formed from the specified components in this order:\n"
        L"      id-prefix + id-base + id-suffix.\n"
        L"      If none is specified, the execution ID defaults to timestamp+pid (UTC).\n"
        L"\n"
        L"Child Event Framing:\n"
        L"  --stdout-event-framing <chunk|lf|newline|crlf>\n"
        L"  --stdout-event-newline-max-bytes <bytes>\n"
        L"  --stderr-child-event-framing <chunk|lf|newline|crlf>\n"
        L"  --stderr-child-event-newline-max-bytes <bytes>\n"
        L"      Select how child output is framed into events.\n"
        L"      chunk preserves the existing read-chunk behavior and is the default.\n"
        L"      lf and newline both select LF; crlf selects an exact CRLF sequence.\n"
        L"      Split child output into events when the configured byte threshold is reached.\n"
        L"      With lf, newline, or crlf framing, an omitted threshold defaults to 524288 bytes (512 KiB).\n"
        L"      Each newline-max-bytes option requires the corresponding framing to be lf, newline, or crlf.\n"
        L"      The threshold is not a strict cap; CRLF recognition may consume one additional byte\n"
        L"      when the threshold is reached with a trailing CR.\n"
        L"\n"
        L"Parent Emission:\n"
        L"      Parent emission determines which events reach the parent process, how they\n"
        L"      are presented, and when or whether they are emitted.\n"
        L"      The option name specifies event sources, output destination, event filter,\n"
        L"      and presentation; <mode> determines the emission timing and condition.\n"
        L"      Example: --stderr-emit-child-raw <mode>\n"
        L"        stderr  -> Event sources: child stderr and SilentRunner diagnostics\n"
        L"        emit    -> Output destination: parent stderr (corresponds to source channel)\n"
        L"        child   -> Event filter: pass only child stderr events\n"
        L"        raw     -> Presentation: Raw\n"
        L"        <mode>  -> Emission mode\n"
        L"      The -child, -sr, and -incl-stdout suffixes determine which events pass the filter.\n"
        L"      Without -raw, Headered presentation is used.\n"
        L"  --stdout-emit <mode>\n"
        L"      Child stdout (Headered).\n"
        L"  --stdout-emit-raw <mode>\n"
        L"      Child stdout (Raw).\n"
        L"  --stderr-emit <mode>\n"
        L"      Child stderr and SilentRunner diagnostics (Headered).\n"
        L"  --stderr-emit-child <mode>\n"
        L"      Child stderr (Headered).\n"
        L"  --stderr-emit-child-raw <mode>\n"
        L"      Child stderr (Raw).\n"
        L"  --stderr-emit-sr <mode>\n"
        L"      SilentRunner diagnostics (Headered).\n"
        L"  --stderr-emit-incl-stdout <mode>\n"
        L"      Child stdout, child stderr, and SilentRunner diagnostics (Headered).\n"
        L"      The five stderr emit options are mutually exclusive.\n"
        L"      --stdout-emit and --stdout-emit-raw are mutually exclusive.\n"
        L"\n"
        L"Emission modes:\n";
    SR::AppendEmitModeHelpForBoth(err);
    err +=
        L"\nPersistent Logging:\n"
        L"      Persistent logging determines which events are written to per-execution\n"
        L"      log files, how they are presented, and where those files are stored.\n"
        L"      The option name specifies event sources, output destination, event filter,\n"
        L"      and presentation; <dir> specifies the output directory path.\n"
        L"      Example: --stderr-dir-child-raw <dir>\n"
        L"        stderr  -> Event sources: child stderr and SilentRunner diagnostics\n"
        L"        dir     -> Output destination: directory containing per-execution log files\n"
        L"        child   -> Event filter: pass only child stderr events\n"
        L"        raw     -> Presentation: Raw (TXT format)\n"
        L"        <dir>   -> Output directory path\n"
        L"      Alternative presentation suffix:\n"
        L"        jsonl   -> Presentation: JSON record (JSONL format)\n"
        L"      The -child, -sr, and -incl-stdout suffixes determine which events pass the filter.\n"
        L"      Without -raw or -jsonl, Headered presentation (TXT format) is used.\n"
        L"  --stdout-dir <dir>\n"
        L"  --stdout-dir-jsonl <dir>\n"
        L"  --stdout-dir-raw <dir>\n"
        L"  --stderr-dir <dir>\n"
        L"  --stderr-dir-jsonl <dir>\n"
        L"  --stderr-dir-child <dir>\n"
        L"  --stderr-dir-child-jsonl <dir>\n"
        L"  --stderr-dir-child-raw <dir>\n"
        L"  --stderr-dir-sr <dir>\n"
        L"  --stderr-dir-sr-jsonl <dir>\n"
        L"  --stderr-dir-incl-stdout <dir>\n"
        L"  --stderr-dir-incl-stdout-jsonl <dir>\n"
        L"      All log destinations may be enabled simultaneously.\n"
        L"      Output directories are created automatically if needed.\n"
        L"      Compatible log files may be used as replay sources for delayed parent emission.\n"
        L"      See https://github.com/jzav/silent-runner/blob/main/docs/parameters.md#buffering for details and examples.\n"
        L"  --jsonl-payload-representation <text|base64|text+base64|base64+text>\n"
        L"      Control payload representation in JSONL logs. Default: text.\n"
        L"      When text representation is requested, invalid UTF-8 child payloads fall back to base64.\n"
        L"      text+base64 and base64+text are equivalent and write both representations when text is valid.\n"
        L"\n"
        L"Log Retention:\n"
        L"  --stdout-dir-keep-log <mode>\n"
        L"  --stderr-dir-keep-log <mode>\n"
        L"  --stderr-dir-child-keep-log <mode>\n"
        L"  --stderr-dir-sr-keep-log <mode>\n"
        L"  --stderr-dir-incl-stdout-keep-log <mode>\n"
        L"      Control when log files are kept or deleted.\n"
        L"      Log retention is configured independently for each event filter, regardless of presentation.\n"
        L"\n"
        L"Keep-log modes:\n";
    SR::AppendKeepLogModeHelp(err);
    err +=
        L"\nBuffering:\n"
        L"  --stdout-max-buffer-bytes <bytes>\n"
        L"  --stderr-max-buffer-bytes <bytes>\n"
        L"  --std-total-max-buffer-bytes <bytes>\n"
        L"      Limit RAM used when buffering stdout/stderr for End/Success/Failure replay.\n"
        L"      stdout/stderr limits are per-stream; std-total-max-buffer-bytes is the total limit.\n"
        L"      Recommended especially when no log file is configured.\n"
        L"\n"
        L"Post-Execution Hooks:\n"
        L"  --run-on-success <path>\n"
        L"  --run-on-failure <path>\n"
        L"      Execute hook file via cmd.exe /d /s /c.\n"
        L"      The file must exist and be directly executable by cmd.exe.\n"
        L"      No arguments are supported; execution context is provided via environment variables only:\n"
        L"      SILENTRUNNER_EXIT_CODE, SILENTRUNNER_EXECUTION_ID,\n"
        L"      SILENTRUNNER_PREPARE_EXIT_CODE, SILENTRUNNER_RUNTIME_EXIT_CODE,\n"
        L"      SILENTRUNNER_ABORTED_ON_RUNTIME_FAILURE (true/false),\n"
        L"      SILENTRUNNER_OUTPUT_WRITE_FAILURES,\n"
        L"      SILENTRUNNER_STDOUT_LOG, SILENTRUNNER_STDOUT_JSONL_LOG,\n"
        L"      SILENTRUNNER_STDOUT_RAW_LOG,\n"
        L"      SILENTRUNNER_STDERR_LOG, SILENTRUNNER_STDERR_JSONL_LOG,\n"
        L"      SILENTRUNNER_STDERR_CHILD_LOG, SILENTRUNNER_STDERR_CHILD_JSONL_LOG,\n"
        L"      SILENTRUNNER_STDERR_CHILD_RAW_LOG,\n"
        L"      SILENTRUNNER_STDERR_SR_LOG, SILENTRUNNER_STDERR_SR_JSONL_LOG,\n"
        L"      SILENTRUNNER_STDERR_INCL_STDOUT_LOG, SILENTRUNNER_STDERR_INCL_STDOUT_JSONL_LOG.\n"
        L"      PREPARE_EXIT_CODE and RUNTIME_EXIT_CODE are provided only when available.\n"
        L"      OUTPUT_WRITE_FAILURES: outputWriteFailures_N=[Target_GLE=number,...].\n"
        L"      Its value contains numeric GLE codes, not error reasons or system messages; no failures: outputWriteFailures_0=[].\n"
        L"      Log environment variables are empty if the corresponding log is not kept after execution\n"
        L"      (see --stdout-dir-keep-log, --stderr-dir-keep-log,\n"
        L"      --stderr-dir-child-keep-log, --stderr-dir-sr-keep-log,\n"
        L"      --stderr-dir-incl-stdout-keep-log).\n"
        L"      The success hook is selected when the exit code before hook launch is 0.\n"
        L"      The failure hook is selected when it is non-zero, including SilentRunner failures.\n"
        L"      Run hooks are started detached. Failure to prepare or launch the selected hook returns exit code 253.\n"
        L"      Hook completion and exit status are not monitored; hook output is not captured.\n"
        L"\n"
        L"Diagnostics:\n"
        L"  --debug\n"
        L"      Enable debug diagnostics.\n"
        L"      Job Object IOCP setup is required; failure returns 255 before child start.\n"
        L"  --verbose\n"
        L"      Enable verbose diagnostics (implies --debug).\n"
        L"  --probe-dir <dir>\n"
        L"      Enables detailed internal probe logging. Intended for development and advanced diagnostics.\n"
        L"      Output format may change between versions.\n"
        L"      Probe logs bypass the ExecutionTimeline and are written directly to the probe log file.\n"
        L"\n"
        L"Help:\n"
        L"  --help\n"
        L"      Show this help message and exit.\n"
        L"\n"
        L"For examples and detailed usage, see https://github.com/jzav/silent-runner#documentation.";
    return err;
}

} // namespace HelpGenerator
